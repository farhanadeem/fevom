#!/bin/sh
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
out=inputs.lock
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

locks="guest/emu/sources.lock guest/sysimage/sources.lock tools/debug-index.lock guest/docker/sources.lock host/docker/tools/tools.lock tests/fixtures/docker-cli.lock"
bases="kernel/builder/Dockerfile guest/sysimage/Dockerfile"
deps="vmm/Cargo.lock guest/go.sum host/go.sum app/Package.resolved"

others() {
	_n=
	for _p in "$@"; do _n="$_n${_n:+ -o} -name $_p"; done
	set -f
	find . \( -name .git -o -name out -o -name target -o -name .build -o -name node_modules \) -prune \
		-o -type f \( $_n \) -print | sed 's|^\./||' | LC_ALL=C sort >"$tmp/found"
	set +f
	: >"$tmp/ignored"
	if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
		git check-ignore --stdin <"$tmp/found" >"$tmp/ignored" || true
		git check-attr --stdin fev-inputs <"$tmp/found" | sed -n 's/: fev-inputs: skip$//p' >>"$tmp/ignored"
	fi
	grep -v -x -F -f "$tmp/ignored" "$tmp/found" || true
}
listed() {
	case " $(echo "$2" | tr '\n' ' ') " in *" $1 "*) return 0 ;; esac
	return 1
}
for f in $(others 'Dockerfile'); do listed "$f" "$bases" || bases="$bases $f"; done
for f in $(others 'go.sum' 'Cargo.lock' 'package-lock.json' 'requirements.txt' 'Package.resolved'); do listed "$f" "$deps" || deps="$deps $f"; done
for f in $(others '*.lock'); do
	case "$f" in inputs.lock | *Cargo.lock | guest/debug/defaultset.lock | guest/debug/defaultset-x86_64.lock) continue ;; esac
	listed "$f" "$locks" || locks="$locks $f"
done

gen() {
	cat <<'HEAD'
# Every pinned third-party input of a build of this commit.
# Generated by tools/gen-lock.sh from the files named in each section; do
# not edit it by hand. `tools/gen-lock.sh --check` fails when it is stale.
#
# toolchain  NAME  VERSION                      what compiles fev's own code; tools/build.sh refuses another
# kernel     VERSION  SHA256                    the upstream kernel tarball (kernel/VERSION)
# base       FILE  IMAGE@DIGEST  SNAPSHOT       a build container: its base image and the dated package snapshot
# deps       FILE  SHA256                       a language lock file, which pins each module or crate by checksum itself
#                                             (Swift's Package.resolved pins each package by its git revision)
# key        FILE  FINGERPRINT  SHA256  SOURCE  a signing key built into fev, which checks what it downloads
# from FILE: source | linked | tool | image | fex | submodule | notice | channel | input | archive | fetch | inside
#                                             a line of that lock file, unchanged
#                                             (channel/input are debug-index.lock's pinned Nix data;
#                                             archive/fetch/inside are guest/k8s/k3s.lock's: the airgap
#                                             archive and k3s the guest fetches, the programs inside k3s)
HEAD
	echo
	echo "toolchain rust $(sed -n 's/^rust //p' tools/toolchains)"
	echo "toolchain go $(sed -n 's/^go //p' tools/toolchains)"
	echo "toolchain swift $(sed -n 's/^swift //p' tools/toolchains)"
	echo "toolchain xcode $(sed -n 's/^xcode //p' tools/toolchains)"
	echo
	(
		. kernel/VERSION
		echo "kernel $KERNEL_VERSION $KERNEL_SHA256"
	)
	echo
	for f in $bases; do
		[ -f "$f" ] || continue
		echo "base $f $(sed -n 's/^FROM \([^ ]*\).*/\1/p' "$f" | head -1) $(grep -o 'snapshot.debian.org/archive/debian/[0-9TZ]*' "$f" | head -1 | sed 's|.*/||')" | sed 's/ *$//'
	done
	echo
	for f in $deps; do
		[ -f "$f" ] && echo "deps $f $(shasum -a 256 "$f" | cut -d' ' -f1)"
	done
	echo
	fpr=$(sed -n 's/^const Fingerprint = "\([0-9A-F]\{40\}\)"$/\1/p' host/images/key.go)
	[ -n "$fpr" ] || {
		echo "gen-lock: no Fingerprint constant in host/images/key.go" >&2
		return 1
	}
	echo "key host/images/lxc-images.asc $fpr $(shasum -a 256 host/images/lxc-images.asc | cut -d' ' -f1) keyserver.ubuntu.com"
	for f in $locks; do
		echo
		echo "# from $f"
		grep -E '^(source|linked|tool|image|fex|submodule|notice|channel|input|archive|fetch|inside)[[:space:]]' "$f" || {
			echo "gen-lock: $f has no source, linked, tool, image, fex, submodule or notice line: teach this script its form, or give it those" >&2
			return 1
		}
	done
}

case "${1:-}" in
"")
	gen >"$out.new" || {
		rm -f "$out.new"
		exit 1
	}
	mv "$out.new" "$out"
	;;
--check)
	gen >/dev/null || exit 1
	gen | diff -u "$out" - >/dev/null 2>&1 || {
		echo "inputs.lock is stale: run tools/gen-lock.sh" >&2
		gen | diff -u "$out" - | head -20 >&2 || true
		exit 1
	}
	;;
*)
	echo "usage: $0 [--check]" >&2
	exit 2
	;;
esac
