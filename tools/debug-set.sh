#!/bin/sh
set -eu

arch=aarch64
index_file=""
while [ $# -gt 0 ]; do
  case "$1" in
    -arch) arch=$2; shift 2 ;;
    -index-file) index_file=$2; shift 2 ;;
    *) echo "debug-set.sh: unknown argument $1" >&2; exit 2 ;;
  esac
done

root=$(cd "$(dirname "$0")/.." && pwd)
case "$arch" in
aarch64) lock="$root/guest/debug/defaultset.lock" ;;
x86_64) lock="$root/guest/debug/defaultset-x86_64.lock" ;;
*) echo "debug-set.sh: -arch aarch64 or x86_64" >&2; exit 2 ;;
esac
prefs="$root/guest/debug/store/prefs.tsv"
: "${index_file:=$root/guest/debug/store/index-${arch}-linux.tsv.zst}"

commands="zsh bash vim nano htop curl strace ip dig lsof ps tcpdump less ls file jq find grep sed awk nsenter ping tree"

hydra_attrs="zsh-autosuggestions zsh-syntax-highlighting zsh-completions cacert"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

echo "debug-set.sh: resolving ${arch} default set from $index_file" >&2
(cd "$root/guest" && "${GO:-go}" build -o "$tmp/fev-debug" ./cmd/fev-debug)
"$tmp/fev-debug" resolve -store "$tmp/store" -index-file "$index_file" $commands \
  | cut -f2 | sort -u > "$tmp/roots"

hydra_base="https://hydra.nixos.org/job/nixpkgs/trunk"
for a in $hydra_attrs; do
  url="$hydra_base/$a.${arch}-linux/latest-finished"
  sp=$(curl -fsSL -H 'Accept: application/json' "$url" \
       | python3 -I -c 'import json, sys; print(json.load(sys.stdin)["buildoutputs"]["out"]["path"])')
  if [ -z "$sp" ]; then
    echo "debug-set.sh: could not resolve $a from Hydra ($url)" >&2
    exit 1
  fi
  echo "$sp" >> "$tmp/roots"
done

sort -u "$tmp/roots" > "$tmp/roots.sorted"
id=$(shasum -a 256 "$tmp/roots.sorted" | cut -c1-16)
rel=$(sed -n 's/^#fev-index-1\t//p' <(zstd -dc "$index_file" 2>/dev/null | head -1) 2>/dev/null || true)

{
  echo "# fev-debug default set ${id}"
  echo "# $(date -u +%Y-%m-%d) fev command index ${rel:-current}"
  echo "# Generated by tools/debug-set.sh. Store paths, not names;"
  echo "# every install of a release fetches the same bytes from the cache."
  echo "# The three zsh plugins and cacert carry no bin/ and come from Hydra latest-finished."
  cat "$tmp/roots.sorted"
} > "$lock"

echo "debug-set.sh: wrote $lock ($(grep -c '^/nix' "$lock") roots, id $id)" >&2

echo "debug-set.sh: checking prefs ($prefs)" >&2
while IFS=$(printf '\t') read -r cmd want; do
  case "$cmd" in ''|'#'*) continue ;; esac
  got=$("$tmp/fev-debug" resolve -store "$tmp/store" -index-file "$index_file" "$cmd" | cut -f2)
  case "$got" in
    *"$want"*) echo "  ok   $cmd -> $got" >&2 ;;
    *) echo "  WARN $cmd wanted *$want* but resolved to $got" >&2 ;;
  esac
done < "$prefs"
