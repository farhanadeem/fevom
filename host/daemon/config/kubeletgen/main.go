package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
)

const version = "v0.37.1"

const out = "daemon/config/kubelet_fields.go"

func main() {
	check := flag.Bool("check", false, "fail if the file is not what this would write")
	flag.Parse()
	cache, err := exec.Command("go", "env", "GOMODCACHE").Output()
	if err != nil {
		fail(err)
	}
	src := filepath.Join(strings.TrimSpace(string(cache)), "k8s.io", "kubelet@"+version, "config", "v1beta1", "types.go")
	text, err := generate(src)
	if err != nil {
		fail(err)
	}
	if *check {
		have, _ := os.ReadFile(out)
		if !bytes.Equal(have, text) {
			fail(fmt.Errorf("%s is not current with %s; run go run ./daemon/config/kubeletgen", out, src))
		}
		return
	}
	if err := os.WriteFile(out, text, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "kubeletgen:", err)
	os.Exit(1)
}

func generate(src string) ([]byte, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, src, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("%v (go mod download k8s.io/kubelet@%s)", err, version)
	}
	types := map[string]ast.Expr{}
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.TYPE {
			continue
		}
		for _, s := range g.Specs {
			ts := s.(*ast.TypeSpec)
			types[ts.Name.Name] = ts.Type
		}
	}
	st, ok := types["KubeletConfiguration"].(*ast.StructType)
	if !ok {
		return nil, fmt.Errorf("%s has no KubeletConfiguration struct", src)
	}
	fields := map[string]string{}
	for _, fl := range st.Fields.List {
		if fl.Tag == nil || len(fl.Names) == 0 {
			continue
		}
		tag := reflect.StructTag(strings.Trim(fl.Tag.Value, "`")).Get("json")
		name, _, _ := strings.Cut(tag, ",")
		if name == "" || name == "-" {
			continue
		}
		fields[name] = kind(fl.Type, types)
	}
	names := make([]string, 0, len(fields))
	for n := range fields {
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by kubeletgen from k8s.io/kubelet@%s's config/v1beta1/types.go; DO NOT EDIT.\n\n", version)
	b.WriteString("package config\n\n")
	fmt.Fprintf(&b, "// kubeletVersion is the k8s.io/kubelet the fields are read from.\nconst kubeletVersion = %q\n\n", version)
	b.WriteString("// kubeletFields are KubeletConfiguration's fields by JSON name, each with\n// the JSON kind its value takes: bool, number, string, array, object.\nvar kubeletFields = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, fields[n])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func kind(e ast.Expr, types map[string]ast.Expr) string {
	switch t := e.(type) {
	case *ast.StarExpr:
		return kind(t.X, types)
	case *ast.ArrayType:
		return "array"
	case *ast.MapType:
		return "object"
	case *ast.StructType:
		return "object"
	case *ast.SelectorExpr:
		if t.Sel.Name == "Duration" {
			return "string"
		}
		return "object"
	case *ast.Ident:
		switch t.Name {
		case "bool":
			return "bool"
		case "string":
			return "string"
		case "int", "int32", "int64", "uint32", "uint64", "float32", "float64":
			return "number"
		}
		if u, ok := types[t.Name]; ok {
			return kind(u, types)
		}
	}
	return "any"
}
