func TestTheWebPortsGoToTheProxyWhileOneServes(t *testing.T) {
	d := direct()
	d.Web = true
	s := d.Script(ParseSave(dockerOnly))
	want := "-A FEV-NAMES -d 198.19.4.1/32 -p tcp -m tcp --dport 80 -j REDIRECT --to-ports 15080\n" +
		"-A FEV-NAMES -d 198.19.4.1/32 -p tcp -m tcp --dport 443 -j REDIRECT --to-ports 15443\n" +
		"-A FEV-NAMES -d 198.19.4.2/32 -p tcp -m tcp --dport 80 -j REDIRECT --to-ports 15080\n" +
		"-A FEV-NAMES -d 198.19.4.2/32 -p tcp -m tcp --dport 443 -j REDIRECT --to-ports 15443\n" +
		"-A FEV-NAMES -d 198.19.4.2/32 -j DNAT --to-destination 198.19.2.2\n"
	if !strings.Contains(s, want) {
		t.Errorf("want\n%s\nin:\n%s", want, s)
	}
	d.HTTPS = false
	if s := d.Script(ParseSave(dockerOnly)); strings.Contains(s, "--dport 443") || !strings.Contains(s, "--dport 80") {
		t.Errorf("HTTPS off:\n%s", s)
	}
}

