func TestAMachinesWebPortsGoToTheProxyUntilItServesThem(t *testing.T) {
	d := direct()
	d.Web = true
	d.Machines = netip.MustParsePrefix("198.19.0.0/24")
	d.MachineTargets = []netip.Addr{netip.MustParseAddr("198.19.0.10"), netip.MustParseAddr("198.19.0.11")}
	d.Unredirected = map[netip.AddrPort]bool{netip.MustParseAddrPort("198.19.0.11:80"): true}
	s := d.Script(ParseSave(dockerOnly))
	got := lines(s)
	for _, want := range []string{
		":FEV-WEB - [0:0]",
		"-A FEV-WEB -d 198.19.0.10/32 -p tcp -m tcp --dport 80 -j REDIRECT --to-ports 15080",
		"-A FEV-WEB -d 198.19.0.10/32 -p tcp -m tcp --dport 443 -j REDIRECT --to-ports 15443",
		"-A FEV-WEB -d 198.19.0.11/32 -p tcp -m tcp --dport 443 -j REDIRECT --to-ports 15443",
		"-A PREROUTING -d 198.19.0.0/24 -j FEV-WEB",
	} {
		if !got[want] {
			t.Errorf("missing %q in:\n%s", want, s)
		}
	}
	for _, never := range []string{"-d 198.19.0.11/32 -p tcp -m tcp --dport 80 ", "OUTPUT -d 198.19.0.0/24", "-d 198.19.0.10/32 -j DNAT"} {
		if strings.Contains(s, never) {
			t.Errorf("%q in:\n%s", never, s)
		}
	}
	applied := strings.Replace(dockerOnly, "-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER\n",
		"-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER\n-A PREROUTING -d 198.19.0.0/24 -j FEV-WEB\n", 1)
	if s := d.Script(ParseSave(applied)); strings.Contains(s, "-A PREROUTING -d 198.19.0.0/24") {
		t.Errorf("the jump made again:\n%s", s)
	}
	d.Web = false
	if s := d.Script(ParseSave(dockerOnly)); strings.Contains(s, "-A FEV-WEB -d") {
		t.Errorf("redirected with no web proxy:\n%s", s)
	}
	d.Web, d.HTTPS = true, false
	if s := d.Script(ParseSave(dockerOnly)); strings.Contains(s, "--dport 443") {
		t.Errorf("443 with HTTPS off:\n%s", s)
	}
}

