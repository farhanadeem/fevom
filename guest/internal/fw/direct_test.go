func TestTheMacsNAT64AddressIsLetInAsTheMacsOwn(t *testing.T) {
	s := direct6().Script(ParseSave(dockerOnly))
	got := lines(s)
	for _, src := range []string{"198.19.3.1/32", "198.19.3.3/32"} {
		for _, want := range []string{
			"-A FEV-DIRECT -s " + src + " -i eth0 -j ACCEPT",
			"-A FEV-DIRECT -d " + src + " -o eth0 -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT",
			"-I INPUT 1 -s " + src + " -i eth0 -j FEV-TUNNEL",
			"-A FEV-DIRECT -s " + src + " -o br-5a1b1016bcf4 -j MASQUERADE",
			"-A POSTROUTING -s " + src + " -j FEV-DIRECT",
		} {
			if !got[want] {
				t.Errorf("missing %q in:\n%s", want, s)
			}
		}
	}
	if strings.Contains(s, "fd5b") {
		t.Errorf("IPv6 in the IPv4 rules:\n%s", s)
	}
	applied := strings.Replace(dockerOnly, "-A DOCKER-USER -j FEV-MACHINES\n",
		"-A INPUT -s 198.19.3.1/32 -i eth0 -j FEV-TUNNEL\n-A INPUT -s 198.19.3.3/32 -i eth0 -j FEV-TUNNEL\n-A DOCKER-USER -j FEV-MACHINES\n-A DOCKER-USER -j FEV-DIRECT\n", 1)
	applied = strings.Replace(applied, "-A POSTROUTING -j FEV-MACHINES",
		"-A POSTROUTING -j FEV-MACHINES\n-A POSTROUTING -s 198.19.3.1/32 -j FEV-DIRECT\n-A POSTROUTING -s 198.19.3.3/32 -j FEV-DIRECT", 1)
	if s := direct6().Script(ParseSave(applied)); strings.Contains(s, "-I INPUT") || strings.Contains(s, "-A POSTROUTING") || strings.Contains(s, "-A DOCKER-USER") {
		t.Errorf("made again:\n%s", s)
	}
}
