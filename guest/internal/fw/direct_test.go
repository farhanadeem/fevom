func direct() Direct {
	return Direct{
		Uplink: "eth0", TunnelMac: netip.MustParseAddr("198.19.3.1"),
		Names: netip.MustParsePrefix("198.19.4.0/22"), Index: netip.MustParseAddr("198.19.4.1"),
		WebHTTP: 15080, WebHTTPS: 15443, HTTPS: true,
		Targets: []NameTarget{
			{Address: netip.MustParseAddr("198.19.4.2"), Target: netip.MustParseAddr("198.19.2.2")},
			{Address: netip.MustParseAddr("198.19.4.3"), Target: netip.MustParseAddr("198.19.65.2")},
		},
	}
}

func lines(s string) map[string]bool {
	m := map[string]bool{}
	for _, l := range strings.Split(s, "\n") {
		m[l] = true
	}
	return m
}

func TestTheDirectPathsRulesBesideDockers(t *testing.T) {
	s := direct().Script(ParseSave(dockerOnly))
	got := lines(s)
	for _, want := range []string{
		"*filter", ":FEV-DIRECT - [0:0]", ":FEV-TUNNEL - [0:0]",
		"-A FEV-DIRECT -s 198.19.3.1/32 -i eth0 -j ACCEPT",
		"-A FEV-DIRECT -d 198.19.3.1/32 -o eth0 -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT",
		"-A DOCKER-USER -j FEV-DIRECT",
		"-A FEV-TUNNEL -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT",
		"-A FEV-TUNNEL -p icmp -j ACCEPT",
		"-A FEV-TUNNEL -p tcp -m multiport --dports 15080,15443 -j ACCEPT",
		"-A FEV-TUNNEL -p tcp -j REJECT --reject-with tcp-reset",
		"-A FEV-TUNNEL -j REJECT --reject-with icmp-port-unreachable",
		"-I INPUT 1 -s 198.19.3.1/32 -i eth0 -j FEV-TUNNEL",
		"*nat", ":FEV-DIRECT - [0:0]", ":FEV-NAMES - [0:0]",
		"-A FEV-DIRECT -s 198.19.3.1/32 -o br-5a1b1016bcf4 -j MASQUERADE",
		"-A FEV-DIRECT -s 198.19.3.1/32 -o br-0c1d2e3f4a5b -j MASQUERADE",
		"-A POSTROUTING -s 198.19.3.1/32 -j FEV-DIRECT",
		"-A FEV-NAMES -d 198.19.4.2/32 -j DNAT --to-destination 198.19.2.2",
		"-A FEV-NAMES -d 198.19.4.3/32 -j DNAT --to-destination 198.19.65.2",
		"-I PREROUTING 1 -d 198.19.4.0/22 -j FEV-NAMES",
		"-I OUTPUT 1 -d 198.19.4.0/22 -j FEV-NAMES",
	} {
		if !got[want] {
			t.Errorf("missing %q in:\n%s", want, s)
		}
	}
	for _, never := range []string{":DOCKER-USER - [0:0]", ":DOCKER-INTERNAL - [0:0]", "-o docker0 -j MASQUERADE", "-j DOCKER-INTERNAL", "REDIRECT"} {
		if strings.Contains(s, never) {
			t.Errorf("%q in:\n%s", never, s)
		}
	}
	if strings.Count(s, "COMMIT\n") != 2 {
		t.Errorf("not two tables:\n%s", s)
	}
}

func TestTheRulesAreMadeAgainWithoutDuplicates(t *testing.T) {
	applied := strings.Replace(dockerOnly, "-A DOCKER-USER -j FEV-MACHINES\n",
		"-A INPUT -s 198.19.3.1/32 -i eth0 -j FEV-TUNNEL\n-A DOCKER-USER -j FEV-MACHINES\n-A DOCKER-USER -j FEV-DIRECT\n", 1)
	applied = strings.Replace(applied, "-A PREROUTING -m addrtype",
		"-A PREROUTING -d 198.19.4.0/22 -j FEV-NAMES\n-A PREROUTING -m addrtype", 1)
	applied = strings.Replace(applied, "-A OUTPUT ! -d 127.0.0.0/8",
		"-A OUTPUT -d 198.19.4.0/22 -j FEV-NAMES\n-A OUTPUT ! -d 127.0.0.0/8", 1)
	applied = strings.Replace(applied, "-A POSTROUTING -j FEV-MACHINES",
		"-A POSTROUTING -j FEV-MACHINES\n-A POSTROUTING -s 198.19.3.1/32 -j FEV-DIRECT", 1)
	s := direct().Script(ParseSave(applied))
	for _, never := range []string{"-A DOCKER-USER -j FEV-DIRECT", "-I INPUT", "-A POSTROUTING", "-I PREROUTING", "-I OUTPUT", "-D "} {
		if strings.Contains(s, never) {
			t.Errorf("%q made again:\n%s", never, s)
		}
	}
	moved := strings.Replace(applied, "-A PREROUTING -d 198.19.4.0/22 -j FEV-NAMES\n-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER",
		"-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER\n-A PREROUTING -d 198.19.4.0/22 -j FEV-NAMES", 1)
	s = direct().Script(ParseSave(moved))
	if !strings.Contains(s, "-D PREROUTING -d 198.19.4.0/22 -j FEV-NAMES\n-I PREROUTING 1 -d 198.19.4.0/22 -j FEV-NAMES\n") || strings.Contains(s, "OUTPUT 1") {
		t.Errorf("not moved back to the top:\n%s", s)
	}
}

