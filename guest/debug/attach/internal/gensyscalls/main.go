package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type entry struct {
	name string
	nr   uint32
}

var reSys = regexp.MustCompile(`^\s*SYS_([A-Z0-9_]+)\s*=\s*(\d+)`)

func parse(path string) ([]entry, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var out []entry
	for _, line := range strings.Split(string(b), "\n") {
		m := reSys.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		nr, err := strconv.ParseUint(m[2], 10, 32)
		if err != nil {
			return nil, err
		}
		out = append(out, entry{strings.ToLower(m[1]), uint32(nr)})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out, nil
}

func modDir() (dir, ver string, err error) {
	d, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/sys").Output()
	if err != nil {
		return "", "", err
	}
	v, _ := exec.Command("go", "list", "-m", "-f", "{{.Version}}", "golang.org/x/sys").Output()
	return strings.TrimSpace(string(d)), strings.TrimSpace(string(v)), nil
}

func main() {
	dir, ver, err := modDir()
	if err != nil {
		fmt.Fprintln(os.Stderr, "locating golang.org/x/sys:", err)
		os.Exit(1)
	}
	base := filepath.Join(dir, "unix")
	arm64, err := parse(filepath.Join(base, "zsysnum_linux_arm64.go"))
	check(err)
	amd64, err := parse(filepath.Join(base, "zsysnum_linux_amd64.go"))
	check(err)

	var sb strings.Builder
	sb.WriteString("// Code generated by debug/attach/internal/gensyscalls; DO NOT EDIT.\n//\n")
	fmt.Fprintf(&sb, "// Source: golang.org/x/sys %s, unix/zsysnum_linux_arm64.go and\n", ver)
	sb.WriteString("// unix/zsysnum_linux_amd64.go — Go's published syscall-number tables,\n")
	sb.WriteString("// generated by that package from the kernel's uapi asm/unistd.h. The names\n")
	sb.WriteString("// are the kernel's, lower-cased with the SYS_ prefix stripped, as libseccomp\n")
	sb.WriteString("// and runc resolve an OCI profile's syscall names on each architecture.\n\n")
	sb.WriteString("package attach\n\n")
	emit := func(name string, es []entry) {
		fmt.Fprintf(&sb, "// %s holds %d syscall name->number pairs, sorted by name.\n", name, len(es))
		fmt.Fprintf(&sb, "var %s = []scEntry{\n", name)
		for _, e := range es {
			fmt.Fprintf(&sb, "\t{%q, %d},\n", e.name, e.nr)
		}
		sb.WriteString("}\n\n")
	}
	emit("arm64Syscalls", arm64)
	emit("amd64Syscalls", amd64)

	out := "syscallnum_gen.go"
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	check(os.WriteFile(out, []byte(strings.TrimRight(sb.String(), "\n")+"\n"), 0o644))
	fmt.Printf("wrote %s: arm64 %d, amd64 %d entries\n", out, len(arm64), len(amd64))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
